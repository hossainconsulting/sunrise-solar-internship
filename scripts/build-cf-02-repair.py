"""Generate cf-02-comment-repair.apex from the tasks' actual stored Descriptions.

05/09/2026. Repairs mechanical damage in the six CF-02 task comments. It does NOT
answer anything: 'did / did not' and 'are / are not' are left as they are and
marked [UNANSWERED], because only Hemayet knows what the customers said.

Fixes applied:
  Fitzgerald  paste landed mid-line, destroying the '--- Update 29/08/2026 ---'
              header and splitting the outcome across two places; 'Beech' -> 'Beach'
  Patel       outcome said 'the two Tran records'
  Clark       'the two Clarke records'; angle brackets around the address
  Murphy      angle brackets around the address
  Tran        'chatswood' -> 'Chatswood'
  all six     the two unanswered either/or lines marked [UNANSWERED]
"""
import json, pathlib, re

SRC = pathlib.Path(r"C:/Users/HEMAYE~1/AppData/Local/Temp/claude"
                   r"/c--Users-Hemayet-Hossain-Salesforce-Program"
                   r"/5b4f8a81-0ed7-4073-b746-75bb84aed23f/scratchpad/tasks.json")
OUT = pathlib.Path(__file__).with_name("cf-02-comment-repair.apex")

# The org holds 'a-EUR"' (U+00E2 U+20AC U+201D) where an em dash was pasted: a UTF-8
# em dash decoded as CP1252 and stored that way. Present on Anderson (x2), Murphy and
# Fitzgerald. One of Anderson's two came from cf-02-anderson-reopen.apex on 03/09 -
# the CLI path mangles non-ASCII going in. So everything written here is ASCII only,
# and the existing mojibake is normalised to a plain hyphen rather than a real dash.
MOJIBAKE = "\u00e2\u20ac\u201d"

REPAIR = ("\r\n\r\n--- Repair 05/09/2026 ---\r\n"
          "Mechanical correction only. No address was changed and nothing was answered "
          "on this task today. The two either/or lines above are still open and are "
          "marked [UNANSWERED]; they close when the customer's own words are written in. "
          "Mojibake from a mangled em dash was normalised to ASCII.")

FITZ_BAD_HEAD = ("--- Update 29/08/2026 --- 0410332598, spoke to Samuel J. Fitzgerald.\r\n"
                 "Confirmed service address as: 23 Beech Rd, Chatswood 2067.\r\n"
                 "Asked open; did / did not prompt with the can\r\n"
                 "This task was marked")
FITZ_GOOD_HEAD = "--- Update 29/08/2026 ---\r\nThis task was marked"

FITZ_BAD_TAIL = ("03-09-2026 03/09/2026 - Rangdidate list.\r\n"
                 "Account updated, Service_Address_Unconfirmed__c cleared.\r\n"
                 "CF-20: customer says the two Fitzgerald records are / are not "
                 "the same household.")
FITZ_GOOD_TAIL = (
    "--- Update 03/09/2026 ---\r\n"
    "Rang 0410 332 598, spoke to Samuel J. Fitzgerald.\r\n"
    "Confirmed service address as: 23 Beach Rd, Chatswood 2067 - unchanged from the "
    "address retained at the 25/08 merge.\r\n"
    "Asked open; did / did not prompt with the candidate list. [UNANSWERED]\r\n"
    "Account updated, Service_Address_Unconfirmed__c cleared.\r\n"
    "CF-20: customer says the two Fitzgerald records are / are not the same household. "
    "[UNANSWERED]")

# per-task literal replacements, applied in order
FIXES = {
    "Fitzgerald": [(FITZ_BAD_HEAD, FITZ_GOOD_HEAD), (FITZ_BAD_TAIL, FITZ_GOOD_TAIL)],
    "Patel":      [("the two Tran records", "the two Joshua J. Patel records")],
    "Clark":      [("the two Clarke records", "the two Daniel J. Clark records"),
                   ("<Campbelltown> <2560>", "Campbelltown 2560")],
    "Murphy":     [("<Campbelltown> <2560>", "Campbelltown 2560")],
    "Tran":       [("111 Sunset Rd, chatswood 2067", "111 Sunset Rd, Chatswood 2067")],
    "Anderson":   [],
}

def mark_unanswered(text):
    """Append [UNANSWERED] to the two either/or lines, once each."""
    out = []
    for line in text.split("\n"):
        stripped = line.rstrip("\r")
        if ("did / did not" in stripped or "are / are not" in stripped) \
                and "[UNANSWERED]" not in stripped:
            line = stripped.rstrip(". ") + ". [UNANSWERED]" + ("\r" if line.endswith("\r") else "")
        out.append(line)
    return "\n".join(out)

def apex_escape(s):
    return (s.replace("\\", "\\\\").replace("'", "\\'")
             .replace("\r", "\\r").replace("\n", "\\n"))

records = json.load(SRC.open())["result"]["records"]
lines = ["// GENERATED by build-cf-02-repair.py on 05/09/2026 - do not hand-edit",
         "// Repairs mechanical damage in the six CF-02 task comments.",
         "// Answers nothing: the either/or lines stay open, marked [UNANSWERED].",
         "List<Task> updates = new List<Task>();", ""]

for r in records:
    name = r["What"]["Name"]
    key = next((k for k in FIXES if k in name), None)
    desc = r["Description"] or ""
    before = desc
    desc = desc.replace(MOJIBAKE, "-")          # normalise first, patterns assume ASCII
    for bad, good in FIXES[key]:
        if bad not in desc:
            lines.append("// WARNING: pattern not found for %s: %r" % (name, bad[:60]))
        desc = desc.replace(bad, good)
    desc = mark_unanswered(desc)
    if desc != before:
        desc += REPAIR
        lines.append("// %s" % name)
        lines.append("updates.add(new Task(Id='%s', Description='%s'));"
                     % (r["Id"], apex_escape(desc)))
        lines.append("")
    else:
        lines.append("// %s - no change needed\n" % name)

lines += ["update updates;",
          "System.debug('FIX>> tasks updated: ' + updates.size());"]

OUT.write_text("\n".join(lines), encoding="utf-8")
print("wrote", OUT, "-", len(records), "tasks examined")
